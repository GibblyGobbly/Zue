# gen_error_codes.py: turns compiler/error_codes.txt into the two Zue files that use it:
#   compiler/error_codes.zu            the table for `zue explain` and the compile-time errors
#   compiler/runtime/zue_rt_codes.zu   lv_code_for(message), for the errors a running program raises
#   docs/errors.md                     the list of codes between its codes:start and codes:end markers
#   python3 tools/gen_error_codes.py [--check]    --check only reports whether the files are current
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "compiler", "error_codes.txt")
OUT_COMPILER = os.path.join(ROOT, "compiler", "error_codes.zu")
OUT_RUNTIME = os.path.join(ROOT, "compiler", "runtime", "zue_rt_codes.zu")
DOC = os.path.join(ROOT, "docs", "errors.md")
HEADER = """# SPDX-License-Identifier: GPL-3.0-or-later
# Copyright (c) 2026 GibblyGobbly
#
# {name}: generated by tools/gen_error_codes.py from compiler/error_codes.txt. Do not edit.
"""


def parse():
    entries = []
    cur = None
    field = None
    for raw in open(SRC).read().split("\n"):
        if raw.startswith("#") or (not raw.strip() and cur is None):
            continue
        if raw.startswith("== "):
            cur = {"code": raw[3:].strip(), "title": "", "match": "", "text": "", "example": "", "fix": ""}
            entries.append(cur)
            field = None
            continue
        if cur is None:
            continue
        if raw.startswith("    ") and field:
            cur[field] += "\n" + raw[4:]
            continue
        if not raw.strip():
            field = None
            continue
        key, _, value = raw.partition(":")
        key = key.strip()
        if key in cur:
            field = key
            cur[key] = value.strip()
        else:
            sys.exit("unknown field in %s: %r" % (cur["code"], raw))
    for e in entries:
        e["match"] = [m.strip() for m in e["match"].split(" | ") if m.strip()]
        for k in ("text", "example", "fix"):
            e[k] = e[k].strip("\n")
        if not e["title"] or not e["match"] or not e["text"] or not e["fix"]:
            sys.exit("entry %s is incomplete" % e["code"])
    codes = [e["code"] for e in entries]
    if len(set(codes)) != len(codes):
        sys.exit("a code is used twice")
    return entries


def lit(text):
    text = text.replace("\\", "\\\\").replace('"', '\\"').replace("{", "\\{").replace("\n", "\\n")
    return '"' + text + '"'


def build_compiler(entries):
    out = [HEADER.format(name="error_codes.zu"), "export const ERROR_CODES = ["]
    for i, e in enumerate(entries):
        sep = "," if i + 1 < len(entries) else ""
        out.append("    {%s: %s, %s: %s, %s: [%s], %s: %s, %s: %s, %s: %s}%s" % (
            lit("code"), lit(e["code"]), lit("title"), lit(e["title"]),
            lit("match"), ", ".join(lit(m) for m in e["match"]),
            lit("text"), lit(e["text"]), lit("example"), lit(e["example"]), lit("fix"), lit(e["fix"]), sep))
    out.append("]")
    out.append("""
# The code of an error message, or null when the message belongs to no family.
export func code_for(msg) {
    for (let e in ERROR_CODES) {
        for (let piece in e.match) {
            if (contains(msg, piece)) {
                return e.code
            }
        }
    }
    return null
}
""")
    return "\n".join(out)


def build_runtime(entries):
    out = [HEADER.format(name="zue_rt_codes.zu"), 'extern("strstr", "ptr", "ptr,ptr")', "",
           "# The code of an error message as a C string, or 0.", "func lv_code_for(msg) {"]
    for e in entries:
        for m in e["match"]:
            out.append("    if (strstr(msg, cstr(%s)) != 0) {\n        return cstr(%s)\n    }" % (lit(m), lit(e["code"])))
    out.append("    return 0\n}\n")
    return "\n".join(out)


def build_doc(entries):
    text = open(DOC).read()
    a = text.index("<!-- codes:start -->")
    b = text.index("<!-- codes:end -->")
    rows = ["", "| Code | Meaning |", "|---|---|"]
    for e in entries:
        rows.append("| `%s` | %s |" % (e["code"], e["title"]))
    rows.append("")
    return text[:a] + "<!-- codes:start -->" + "\n".join(rows) + text[b:]


def main():
    entries = parse()
    files = {OUT_COMPILER: build_compiler(entries), OUT_RUNTIME: build_runtime(entries), DOC: build_doc(entries)}
    stale = [p for p, t in files.items() if not os.path.exists(p) or open(p).read() != t]
    if "--check" in sys.argv:
        if stale:
            print("out of date: " + ", ".join(os.path.relpath(p, ROOT) for p in stale) + " (run tools/gen_error_codes.py)")
            sys.exit(1)
        print("error code files are current (%d codes)" % len(entries))
        return
    for p, t in files.items():
        open(p, "w").write(t)
    print("wrote %d codes" % len(entries))


main()
